/** Decodifica un template dalla sua forma hex (48 char = 24 byte = 192 bit,
 *  MSB-first: bit 7 del primo byte = pixel (0,0), riga-major). Layout bit:
 *  gruppo g = righe 4g..4g+3, 12 bit per riga (bit x = colonna x). */
internal fun shT(font: String, digit: String, hex: String): ShTpl {
    val bits = LongArray(4)
    var idx = 0
    for (byteIndex in 0 until 24) {
        val byte = hex.substring(byteIndex * 2, byteIndex * 2 + 2).toInt(16)
        for (b in 0 until 8) {
            if (((byte shr (7 - b)) and 1) == 1) {
                val g = idx / 48
                bits[g] = bits[g] or (1L shl (idx % 48))
            }
            idx++
        }
    }
    return ShTpl(font, digit[0], bits)
}
